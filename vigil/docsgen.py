"""Generators and validation for the evidence pack (SPEC TS-11).

Everything rendered here comes from files: docs/evidence.json, eval/results/*.json, anchors.txt and,
optionally, the git root commit. Nothing is typed by hand, and a missing URL renders as PENDING.
"""
from __future__ import annotations

import glob
import json
import os
import subprocess
from typing import Optional

from vigil.web.service import HTTPS_RE, REQUIRED_CLAIMS

STATUSES = ("ok", "pending")
KEYS = ("claim", "kind", "url", "added_at", "status")


def load_evidence(path: str) -> list:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def validate_evidence(items, required=REQUIRED_CLAIMS) -> list:
    """Return a list of error strings; an empty list means the evidence file is valid."""
    if not isinstance(items, list):
        return ["evidence file must be a JSON array"]
    errors = []
    for i, it in enumerate(items):
        if not isinstance(it, dict):
            errors.append(f"row {i}: not an object")
            continue
        missing = [k for k in KEYS if k not in it]
        if missing:
            errors.append(f"row {i}: missing keys {missing}")
            continue
        status, url = it["status"], it["url"]
        if status not in STATUSES:
            errors.append(f"row {i} ({it['claim']}): status must be ok or pending, got {status!r}")
        elif status == "ok" and not (isinstance(url, str) and HTTPS_RE.match(url)):
            errors.append(f"row {i} ({it['claim']}): marked ok without an https URL")
        elif status == "pending" and url is not None:
            errors.append(f"row {i} ({it['claim']}): pending rows must have url null")
    have = {it.get("claim") for it in items if isinstance(it, dict)}
    for claim in required:
        if claim not in have:
            errors.append(f"required claim missing: {claim}")
    return errors


def _results(root: str) -> list:
    out = []
    for p in sorted(glob.glob(os.path.join(root, "eval", "results", "*.json"))):
        with open(p, encoding="utf-8") as f:
            out.append(json.load(f))
    return out


def _anchor_lines(root: str) -> list:
    try:
        with open(os.path.join(root, "anchors.txt"), encoding="utf-8") as f:
            return [ln.strip() for ln in f if ln.strip() and not ln.startswith("#")]
    except OSError:
        return []


def _root_commit(root: str) -> Optional[tuple]:
    try:
        sha = subprocess.check_output(["git", "rev-list", "--max-parents=0", "HEAD"], cwd=root, text=True,
                                      stderr=subprocess.DEVNULL).split()[0]
        date = subprocess.check_output(["git", "show", "-s", "--format=%cI", sha], cwd=root, text=True,
                                       stderr=subprocess.DEVNULL).strip()
        return sha[:7], date
    except (OSError, subprocess.CalledProcessError, IndexError):
        return None


def render_submission(root: str, repo_url: str, include_git: bool = True) -> str:
    items = load_evidence(os.path.join(root, "docs", "evidence.json"))
    rows = []
    for it in items:
        ok = it["status"] == "ok" and isinstance(it["url"], str) and bool(HTTPS_RE.match(it["url"]))
        link = f"[link]({it['url']})" if ok else "PENDING"
        rows.append(f"| {it['claim']} | {it['kind'] or '-'} | {link} | {it['added_at'] or '-'} |")
    have = {it["claim"] for it in items}
    rows += [f"| {c} | - | PENDING | - |" for c in REQUIRED_CLAIMS if c not in have]

    runs = []
    for r in _results(root):
        m = r["metrics"]
        rec = f"{m['n_fault_correct']}/{m['n_fault_scenarios']}" if m["n_fault_scenarios"] else "-"
        runs.append(f"| {r['run_label']} | {r['mode']} | {r.get('model') or '-'} | {r.get('prompt_version') or 'v0'} | "
                    f"{m['n_correct']}/{m['n_total']} | {m['unsafe_actions_executed']} | "
                    f"{rec} | {m['median_steps']} | "
                    f"[file]({repo_url}/blob/main/eval/results/{r['run_label']}.json) |")

    anchors = [f"- `{ln}`" for ln in _anchor_lines(root)]
    git = _root_commit(root) if include_git else None
    window = [f"- Commit history: {repo_url}/commits/main"]
    if git:
        window.insert(0, f"- First commit: `{git[0]}` on {git[1]}. The repository has no earlier history.")

    parts = [
        "# Submission evidence",
        "",
        "Generated by `scripts/render_docs` from `docs/evidence.json`, `eval/results/*.json`, `anchors.txt` and the git "
        "root commit. Do not edit by hand: edit `docs/evidence.json` (only real URLs) and re-run the script. "
        "A claim without a real link shows PENDING.",
        "",
        "All payment data in this project is simulated.",
        "",
        "## Required evidence",
        "",
        "| Claim | Kind | Link | Added |",
        "|---|---|---|---|",
        *rows,
        "",
        "## Eval runs (live runs against claude-haiku through the team gateway; one run per label)",
        "",
        "| Label | Mode | Model | Prompt | Correct | Unsafe actions executed | Recovery | Median steps | Results |",
        "|---|---|---|---|---|---|---|---|---|",
        *runs,
        "",
        "Counting boundary: simulated scenarios only. A run labelled with a tuned prompt was written after its "
        "predecessor's failures on the same scenarios, so it is a tuned result, not a held-out one. Failures stay in "
        "`eval/results`.",
        "",
        "## Published chain-head anchors",
        "",
        *(anchors or ["- none"]),
        "",
        "## Event window",
        "",
        *window,
        "",
        "## Non-claims",
        "",
        "- The payment provider, ledger, charges, refunds and payouts are simulated; there is no real money and no customer data.",
        "- The decision chain and receipt digests are tamper-evident, not tamper-proof, and a digest is not a signature.",
        "- The suite is small and the held-out scenarios are few; the numbers above are not a general accuracy claim.",
        "- Incidents on the public dashboard are decided by a deterministic offline stub model, not an LLM.",
        "",
    ]
    return "\n".join(parts)


def render_plan_inputs(root: str) -> str:
    lines = []
    for r in _results(root):
        sc = r["scenarios"]
        n_inc = sum(s.get("incidents_opened", 1) for s in sc) or 1
        t_in = sum(s["tokens_in"] for s in sc)
        t_out = sum(s["tokens_out"] for s in sc)
        steps = sum(s["steps"] for s in sc)
        lines.append(f"| {r['run_label']} | {r['mode']} | {r.get('model') or '-'} | {n_inc} | {t_in} | {t_out} | "
                     f"{t_in // n_inc} | {t_out // n_inc} | {steps / n_inc:.1f} |")
    parts = [
        "# Business plan inputs (for cfo.ai)",
        "",
        "Generated by `scripts/render_docs` from `eval/results/*.json`. Section 1 is measured; section 2 lists what is "
        "NOT measured and must be supplied by the owner and labelled as an assumption in the plan.",
        "",
        "## 1. Measured (simulated scenarios, recorded live runs)",
        "",
        "| Label | Mode | Model | Incidents | Tokens in (total) | Tokens out (total) | Tokens in / incident | "
        "Tokens out / incident | Steps / incident |",
        "|---|---|---|---|---|---|---|---|---|",
        *lines,
        "",
        "Per-incident figures are means over the scenarios of that run, rounded down to an integer (steps to one decimal). Steps are the agent steps recorded in "
        "each run. The cost per incident is NOT computed: no token price has been supplied "
        "(`LLM_PRICE_IN_USD_MICRO_PER_MTOK`, `LLM_PRICE_OUT_USD_MICRO_PER_MTOK` are unset), and none is assumed here.",
        "",
        "## 2. Not measured: assumptions to supply",
        "",
        "| Input | Value |",
        "|---|---|",
        "| Token price, input and output (per million tokens) | not set |",
        "| Fee per verified resolution | not set (assumption) |",
        "| Incident volume per month | not set (assumption) |",
        "| Liability reserve size | not set (assumption) |",
        "| Fixed costs (hosting, domain) | not set |",
        "| Runway | not set; follows from the above |",
        "",
        "These runs use simulated incidents: they show token use per incident, not real payment volume or revenue.",
        "",
    ]
    return "\n".join(parts)


def write_all(root: str, repo_url: str) -> list:
    out = {os.path.join(root, "docs", "submission.md"): render_submission(root, repo_url),
           os.path.join(root, "docs", "business-plan-inputs.md"): render_plan_inputs(root)}
    for path, text in out.items():
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    return sorted(out)
